        /// Pixel (x, y) avec y = 0 en bas ; transparent : alpha 0.
        public static Color32 Pixel(string id, int x, int y)
        {
            string[] d;
            if (!Dessins.TryGetValue(id, out d)) return new Color32(0, 0, 0, 0);
            int ligne = d.Length - 1 - y;
            if (ligne < 0 || ligne >= d.Length || x < 0 || x >= d[ligne].Length) return new Color32(0, 0, 0, 0);
            Color32 c;
            return Couleurs.TryGetValue(d[ligne][x], out c) ? c : new Color32(0, 0, 0, 0);
        }

